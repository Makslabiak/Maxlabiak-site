/**
 * «Гарантия 2 года», «гарантия 24 месяца» — срок числом, а не просто слово.
 * ВАЖНО: класс [а-яё], а не \w. В JavaScript \w — это [A-Za-z0-9_],
 * кириллицу он не матчит, и с \w это выражение не срабатывало никогда.
 * Варианты окончаний идут от длинного к короткому: чередование в регулярке
 * берёт первое подходящее, и при порядке (год|года) из «3 года»
 * захватилось бы только «3 год».
 */
export const WARRANTY_TERM_RE =
  /гарант[а-яё]*\s*(—|-|–|:)?\s*(\d+)\s*(года|годa|год|лет|месяцев|месяца|месяц|мес)/i;

